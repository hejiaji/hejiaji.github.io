function transliterate(word) {
    // Normalise diacritics, strip apostrophes, lowercase
    const s = word.normalize("NFD").replace(/[\u0300-\u036f]/g, "")
        .replace(/['ʼ`]/g, "").toLowerCase().replace(/[^a-z]/g, "");
    let out = "";
    let i = 0;
    while (i < s.length) {
        let matched = false;
        for (const [pat, zh] of PHON_MAP) {
            if (s.startsWith(pat, i)) {
                out += zh;
                i += pat.length;
                matched = true;
                break;
            }
        }
        if (!matched) i++;  // skip unknown
    }
    return out || word;
}

function transliterateFullName(name) {
    // Split into words, transliterate each, join with "·"
    const parts = name.split(/[\s\-]+/).filter(Boolean);
    return parts.map(transliterate).join("·");
}

/* Lookup helpers — return Chinese if mapped (Tier 1 or 2),
   otherwise fall back to phonetic transliteration (Tier 3),
   otherwise return original. */
function teamZh(name) { return TEAM_ZH[name] || name; }

function clubZh(name) {
    if (CLUB_ZH[name]) return CLUB_ZH[name];
    // Strip common suffixes and try again
    const stripped = name.replace(/\s+(FC|CF|SC|AFC|AC|FK|SK|RC|US|CA|EC|CR|UD|CD|CFC|BC|HSC|SCO)\s*$/i, "")
                         .replace(/^(FC|CF|SC|AFC|AC|FK|SK|RC|US|CA|EC|CR|CFC|1\.\s*FC|1\.\s*FSV)\s+/i, "");
    if (CLUB_ZH[stripped]) return CLUB_ZH[stripped];
    return name;  // No transliteration for clubs — keep Latin
}

function playerZh(name) {
    if (PLAYER_ZH[name]) return PLAYER_ZH[name];
    // Try matching just surname
    const parts = name.split(/\s+/);
    const last = parts[parts.length - 1];
    if (PLAYER_ZH[last]) return PLAYER_ZH[last];
    // Fall back to phonetic
    return transliterateFullName(name);
}

